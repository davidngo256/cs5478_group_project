"""Dex-Net-style antipodal grasp sampling on a triangle mesh (object frame).

A candidate is a pair of contacts (p1, n1), (p2, n2) plus the closing axis. Candidates are
generated by picking a surface point, casting a ray into the object within `max_off_normal`
degrees of the inward normal, and taking the exit point as the second contact. The
off-normal perturbation is deliberate: it produces a mix of good and mediocre grasps, so
that scoring methods have something to separate.
"""
from __future__ import annotations

from dataclasses import dataclass

import numpy as np
import trimesh

PANDA_MAX_WIDTH = 0.08     # Panda gripper opening [m]
MIN_WIDTH = 0.004          # thinner than this and the pads collide with each other


@dataclass(frozen=True)
class GraspCandidate:
    p1: np.ndarray
    n1: np.ndarray          # inward unit normal at p1
    p2: np.ndarray
    n2: np.ndarray
    axis: np.ndarray        # unit vector from p1 to p2 (closing axis)
    width: float
    gen_score: float        # generator's own preference (mu-independent), higher is better

    @property
    def contacts(self):
        return [(self.p1, self.n1), (self.p2, self.n2)]

    @property
    def centre(self) -> np.ndarray:
        return 0.5 * (self.p1 + self.p2)

    def misalignment_deg(self) -> float:
        a1 = np.degrees(np.arccos(np.clip(self.axis @ self.n1, -1, 1)))
        a2 = np.degrees(np.arccos(np.clip(-self.axis @ self.n2, -1, 1)))
        return float(max(a1, a2))


def _inward_normals(mesh: trimesh.Trimesh, face_ids: np.ndarray) -> np.ndarray:
    # trimesh face normals point outward for a consistently wound mesh
    return -mesh.face_normals[face_ids]


def sample_candidates(mesh: trimesh.Trimesh, n: int, rng: np.random.Generator, *,
                      max_width: float = PANDA_MAX_WIDTH, max_off_normal_deg: float = 25.0,
                      max_tries: int = 50_000, table_up: np.ndarray | None = None) -> list[GraspCandidate]:
    """Sample n antipodal candidates. `table_up` (object-frame unit vector) is only used to
    compute gen_score, which prefers grasps that close horizontally near the centroid."""
    intersector = mesh.ray
    out: list[GraspCandidate] = []
    tries = 0
    batch = max(64, 4 * n)
    while len(out) < n and tries < max_tries:
        tries += batch
        pts, fids = trimesh.sample.sample_surface(mesh, batch, seed=int(rng.integers(2**31)))
        n1s = _inward_normals(mesh, fids)
        # perturb the closing direction within the cone
        ang = np.deg2rad(rng.uniform(0.0, max_off_normal_deg, size=batch))
        rand = rng.normal(size=(batch, 3))
        t = np.cross(n1s, rand)
        t /= np.linalg.norm(t, axis=1, keepdims=True)
        dirs = np.cos(ang)[:, None] * n1s + np.sin(ang)[:, None] * t
        origins = pts + 1e-4 * dirs                       # step inside to avoid self-hit
        locs, idx_ray, idx_tri = intersector.intersects_location(origins, dirs, multiple_hits=True)
        if len(idx_ray) == 0:
            continue
        # farthest exit along each ray = opposite side of the object
        dist = np.einsum("ij,ij->i", locs - origins[idx_ray], dirs[idx_ray])
        order = np.lexsort((-dist, idx_ray))
        idx_ray, locs, idx_tri, dist = idx_ray[order], locs[order], idx_tri[order], dist[order]
        first = np.r_[True, idx_ray[1:] != idx_ray[:-1]]
        cos_max = np.cos(np.deg2rad(max_off_normal_deg))
        for i, p2, tri in zip(idx_ray[first], locs[first], idx_tri[first]):
            p1, n1, d = np.asarray(pts[i], float), n1s[i], dirs[i]
            p2 = np.asarray(p2, float)
            w = float(np.linalg.norm(p2 - p1))
            if not (MIN_WIDTH <= w <= max_width):
                continue
            n2 = -mesh.face_normals[tri]
            if -d @ n2 < cos_max:             # second contact must also be within the off-normal cone
                continue
            out.append(GraspCandidate(p1, n1, p2, n2, d, w, 0.0))
            if len(out) >= n:
                break
    if len(out) < n:
        raise RuntimeError(f"only {len(out)} of {n} candidates found after {tries} tries")
    return _assign_gen_scores(out, mesh, table_up)


def _assign_gen_scores(cands: list[GraspCandidate], mesh: trimesh.Trimesh, table_up) -> list[GraspCandidate]:
    """A mu-independent ordering a simple generator might produce: prefer closing axes that are
    horizontal (grasp from above) and contacts near the centroid. Small random noise breaks ties."""
    up = np.array([0.0, 0.0, 1.0]) if table_up is None else np.asarray(table_up, float)
    rho = 0.5 * np.max(mesh.extents)
    scored = []
    for c in cands:
        horiz = 1.0 - abs(c.axis @ up)                          # 1 = horizontal closing axis
        near = 1.0 - min(np.linalg.norm(c.centre) / rho, 1.0)   # 1 = at the centroid
        scored.append(GraspCandidate(c.p1, c.n1, c.p2, c.n2, c.axis, c.width, float(0.6 * horiz + 0.4 * near)))
    return scored


def transform_candidate(c: GraspCandidate, R: np.ndarray, t: np.ndarray) -> GraspCandidate:
    """Apply a rigid transform (object frame -> world) to a candidate."""
    return GraspCandidate(R @ c.p1 + t, R @ c.n1, R @ c.p2 + t, R @ c.n2, R @ c.axis, c.width, c.gen_score)
